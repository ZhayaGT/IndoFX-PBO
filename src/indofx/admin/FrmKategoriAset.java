    private void btnTambahKategoriActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahKategoriActionPerformed
        DlgTambahEditKategori dialog = new DlgTambahEditKategori(this, true);
        dialog.setDataKategori("", "", "Aktif", false);
        dialog.setLocationRelativeTo(this);
        dialog.setVisible(true);

        if (dialog.tersimpan) {
            DefaultTableModel model = (DefaultTableModel) tblKategori.getModel();
            model.addRow(new Object[]{
                generateIdKategori(),
                dialog.hasilNama,
                dialog.hasilSlug,
                dialog.hasilStatusKategori
            });
            int row = model.getRowCount() - 1;
            tblKategori.setRowSelectionInterval(row, row);
            JOptionPane.showMessageDialog(this, "Kategori \"" + dialog.hasilNama + "\" berhasil ditambahkan!");
        }
    }//GEN-LAST:event_btnTambahKategoriActionPerformed

    private void btnEditKategoriActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditKategoriActionPerformed
        int row = tblKategori.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Silakan klik/pilih salah satu baris kategori pada tabel terlebih dahulu!",
                    "Belum Ada Baris Dipilih",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        String id     = String.valueOf(tblKategori.getValueAt(row, 0));
        String nama   = String.valueOf(tblKategori.getValueAt(row, 1));
        String slug   = String.valueOf(tblKategori.getValueAt(row, 2));
        String status = String.valueOf(tblKategori.getValueAt(row, 3));

        DlgTambahEditKategori dialog = new DlgTambahEditKategori(this, true);
        dialog.setDataKategori(nama, slug, status, true);
        dialog.setLocationRelativeTo(this);
        dialog.setVisible(true);

        if (dialog.tersimpan) {
            tblKategori.setValueAt(dialog.hasilNama, row, 1);
            tblKategori.setValueAt(dialog.hasilSlug, row, 2);
            tblKategori.setValueAt(dialog.hasilStatusKategori, row, 3);
            JOptionPane.showMessageDialog(this, "Kategori " + id + " berhasil diperbarui!");
        }
    }//GEN-LAST:event_btnEditKategoriActionPerformed

    private void btnHapusKategoriActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusKategoriActionPerformed
        int row = tblKategori.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Silakan klik/pilih salah satu baris kategori pada tabel terlebih dahulu!",
                    "Belum Ada Baris Dipilih",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        String id   = String.valueOf(tblKategori.getValueAt(row, 0));
        String nama = String.valueOf(tblKategori.getValueAt(row, 1));

        DlgHapusKategori dialog = new DlgHapusKategori(this, true);
        dialog.setDataKategori(nama);
        dialog.setLocationRelativeTo(this);
        dialog.setVisible(true);

        if (dialog.terhapus) {
            ((DefaultTableModel) tblKategori.getModel()).removeRow(row);
            JOptionPane.showMessageDialog(this, "Kategori " + id + " berhasil dihapus.");
        }
    }//GEN-LAST:event_btnHapusKategoriActionPerformed

