    /**
     * Membuat ID kategori baru berurutan (KAT-06, KAT-07, ...) berdasarkan isi tabel.
     */
    private String generateIdKategori() {
        int max = 0;
        for (int i = 0; i < tblKategori.getRowCount(); i++) {
            String id = String.valueOf(tblKategori.getValueAt(i, 0));
            String angka = id.replaceAll("\\D+", "");
            if (!angka.isEmpty()) {
                max = Math.max(max, Integer.parseInt(angka));
            }
        }
        return String.format("KAT-%02d", max + 1);
    }

