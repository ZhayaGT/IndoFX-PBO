    /**
     * Mengisi info pengguna dan pilihan role/status dari baris tabel yang dipilih.
     */
    public void setDataUser(String id, String nama, String email, String role, String statusAkun) {
        lblInfoUser.setText(nama + " (" + id + ")");
        lblEmailUser.setText(email);
        if (role != null) {
            cmbRole.setSelectedItem(role);
        }
        if (statusAkun != null) {
            cmbStatusAkun.setSelectedItem(statusAkun);
        }
    }

