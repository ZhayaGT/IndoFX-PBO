    private void btnTinjauActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTinjauActionPerformed
        int row = tblAntrean.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Silakan klik/pilih salah satu baris aset pada tabel terlebih dahulu!",
                    "Belum Ada Baris Dipilih",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        String id      = tblAntrean.getValueAt(row, 0).toString();
        String nama    = tblAntrean.getValueAt(row, 1).toString();
        String kreator = tblAntrean.getValueAt(row, 2).toString();
        String harga   = tblAntrean.getValueAt(row, 4).toString();

        DlgQuickModerasi dialog = new DlgQuickModerasi(this, true);
        dialog.setDataAset(id, nama, kreator, harga);
        dialog.setLocationRelativeTo(this);
        dialog.setVisible(true);

        if (dialog.hasilStatus != null) {
            tblAntrean.setValueAt(dialog.hasilStatus, row, 5);
            JOptionPane.showMessageDialog(this, "Status aset " + id + " berhasil diubah menjadi " + dialog.hasilStatus + "!");
        }
    }//GEN-LAST:event_btnTinjauActionPerformed

