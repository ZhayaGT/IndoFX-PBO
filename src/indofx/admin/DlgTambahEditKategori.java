    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        String nama = txtNamaKategori.getText().trim();
        if (nama.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Nama kategori wajib diisi!",
                    "Data Belum Lengkap",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            txtNamaKategori.requestFocus();
            return;
        }

        String slug = txtSlug.getText().trim();
        if (slug.isEmpty()) {
            slug = nama.toLowerCase().replaceAll("[^a-z0-9]+", "-").replaceAll("(^-|-$)", "");
            txtSlug.setText(slug);
        }

        hasilNama = nama;
        hasilSlug = slug;
        hasilStatusKategori = String.valueOf(cmbStatusKategori.getSelectedItem());
        tersimpan = true;
        dispose();
    }//GEN-LAST:event_btnSimpanActionPerformed

