    /**
     * Mengisi detail lengkap aset dari baris tabel yang dipilih.
     */
    public void setDataAset(String id, String nama, String kreator, String emailKreator,
            String kategori, String harga, String spesifikasi, String status, String catatanLama) {
        setTitle("Detail & Persetujuan Aset — " + id);
        lblValId.setText(":  " + id);
        lblValNama.setText(":  " + nama);

        String kreatorText = (emailKreator != null && !emailKreator.isEmpty())
                ? kreator + " (" + emailKreator + ")"
                : kreator;
        lblValKreator.setText(":  " + kreatorText);
        lblValKategori.setText(":  " + kategori);
        lblValHarga.setText(":  " + harga);
        lblValSpesifikasi.setText(":  " + spesifikasi);

        Color statusColor;
        String statusDesc;
        if ("DISETUJUI".equalsIgnoreCase(status) || "AKTIF".equalsIgnoreCase(status)) {
            statusColor = new Color(22, 163, 74);
            statusDesc = status.toUpperCase() + " (Tayang di Marketplace)";
        } else if ("DITOLAK".equalsIgnoreCase(status)) {
            statusColor = new Color(220, 38, 38);
            statusDesc = "DITOLAK (Perlu Perbaikan Kreator)";
        } else {
            statusColor = new Color(234, 88, 12);
            statusDesc = "PENDING (Menunggu Moderasi)";
        }
        lblKeyStatus.setForeground(statusColor);
        lblValStatus.setForeground(statusColor);
        lblValStatus.setText(":  " + statusDesc);

        txtCatatan.setText(catatanLama != null ? catatanLama : "");
    }

