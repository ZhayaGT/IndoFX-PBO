-- 1. users (Login + Menu 4: Manajemen Pengguna)
CREATE TABLE public.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name varchar(120) NOT NULL,
  email varchar(150) NOT NULL,
  password varchar(255) NOT NULL,
  role varchar(20) NOT NULL DEFAULT 'Admin'
    CHECK (role IN ('Kreator', 'Pembeli', 'Admin')),
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT users_pkey PRIMARY KEY (id),
  CONSTRAINT uq_users_email UNIQUE (email)
);

-- 2. seller profiles (Identitas Kreator / Toko)
CREATE TABLE public.seller_profiles (
  user_id bigint NOT NULL,
  store_name varchar(120) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT seller_profiles_pkey PRIMARY KEY (user_id),
  CONSTRAINT fk_seller_profiles_user FOREIGN KEY (user_id)
    REFERENCES public.users(id) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- 3. categories (Menu 3: Kategori Aset)
CREATE TABLE public.categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name varchar(100) NOT NULL,
  slug varchar(100) NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  CONSTRAINT categories_pkey PRIMARY KEY (id),
  CONSTRAINT uq_categories_name UNIQUE (name),
  CONSTRAINT uq_categories_slug UNIQUE (slug)
);

-- 4. assets (Menu 1: Dashboard & Menu 2: Moderasi Aset)
CREATE TABLE public.assets (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  seller_id bigint NOT NULL,
  category_id bigint NOT NULL,
  title varchar(200) NOT NULL,
  specification text NOT NULL,
  price integer NOT NULL CHECK (price >= 0),
  status varchar(20) NOT NULL DEFAULT 'PENDING'
    CHECK (status IN ('PENDING', 'AKTIF', 'DITOLAK')),
  admin_note text,
  reviewed_by bigint,
  reviewed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT assets_pkey PRIMARY KEY (id),
  CONSTRAINT fk_assets_seller FOREIGN KEY (seller_id)
    REFERENCES public.seller_profiles(user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_assets_category FOREIGN KEY (category_id)
    REFERENCES public.categories(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_assets_reviewer FOREIGN KEY (reviewed_by)
    REFERENCES public.users(id) ON UPDATE CASCADE ON DELETE SET NULL
);

-- 5. reports (Menu 5: Persetujuan & Laporan Masalah)
CREATE TABLE public.reports (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  reporter_id bigint NOT NULL,
  asset_id bigint DEFAULT NULL,
  report_type varchar(30) NOT NULL DEFAULT 'asset_issue'
    CHECK (report_type IN ('asset_issue', 'seller_application')),
  subject varchar(200) NOT NULL,
  description text NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'DITINJAU'
    CHECK (status IN ('DITINJAU', 'SELESAI', 'DITOLAK')),
  admin_note text,
  reviewed_by bigint,
  reviewed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT reports_pkey PRIMARY KEY (id),
  CONSTRAINT fk_reports_reporter FOREIGN KEY (reporter_id)
    REFERENCES public.users(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_reports_asset FOREIGN KEY (asset_id)
    REFERENCES public.assets(id) ON UPDATE CASCADE ON DELETE SET NULL,
  CONSTRAINT fk_reports_reviewer FOREIGN KEY (reviewed_by)
    REFERENCES public.users(id) ON UPDATE CASCADE ON DELETE SET NULL
);

-- 6. transactions (Menu 1 KPI & Menu 6: Monitoring Transaksi)
CREATE TABLE public.transactions (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  buyer_id bigint NOT NULL,
  invoice_number varchar(50) NOT NULL,
  commission_rate numeric(5,2) NOT NULL DEFAULT 10.00
    CHECK (commission_rate >= 0 AND commission_rate <= 100),
  status varchar(20) NOT NULL DEFAULT 'MENUNGGU PEMBAYARAN'
    CHECK (status IN ('MENUNGGU PEMBAYARAN', 'LUNAS')),
  paid_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT transactions_pkey PRIMARY KEY (id),
  CONSTRAINT uq_transactions_invoice UNIQUE (invoice_number),
  CONSTRAINT fk_transactions_buyer FOREIGN KEY (buyer_id)
    REFERENCES public.users(id) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- 7. transaction details (Item Aset per Transaksi)
CREATE TABLE public.transaction_details (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  transaction_id bigint NOT NULL,
  asset_id bigint NOT NULL,
  price integer NOT NULL CHECK (price >= 0),
  CONSTRAINT transaction_details_pkey PRIMARY KEY (id),
  CONSTRAINT uq_trx_detail_asset UNIQUE (transaction_id, asset_id),
  CONSTRAINT fk_trx_details_transaction FOREIGN KEY (transaction_id)
    REFERENCES public.transactions(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_trx_details_asset FOREIGN KEY (asset_id)
    REFERENCES public.assets(id) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- 8. Views untuk java swing

-- A. View Menu 1 & Menu 2 (Moderasi Aset)
CREATE OR REPLACE VIEW public.v_assets_moderation AS
SELECT
  a.id,
  'AST-' || a.id AS asset_code,
  a.title,
  a.specification,
  a.price,
  a.status,
  a.admin_note,
  a.reviewed_by,
  a.reviewed_at,
  a.created_at,
  c.id AS category_id,
  c.name AS category_name,
  sp.user_id AS seller_id,
  sp.store_name AS creator_name,
  u.email AS creator_email
FROM public.assets a
JOIN public.categories c ON c.id = a.category_id
JOIN public.seller_profiles sp ON sp.user_id = a.seller_id
JOIN public.users u ON u.id = sp.user_id;

-- B. View Menu 3 (Kategori + Hitung Jumlah Aset Otomatis)
CREATE OR REPLACE VIEW public.v_categories_summary AS
SELECT
  c.id,
  c.name,
  c.slug,
  c.is_active,
  COUNT(a.id) AS asset_count
FROM public.categories c
LEFT JOIN public.assets a ON a.category_id = c.id
GROUP BY c.id;

-- C. View Menu 4 (Daftar Pengguna)
CREATE OR REPLACE VIEW public.v_users_list AS
SELECT
  u.id,
  'USR-' || LPAD(u.id::text, 2, '0') AS user_code,
  u.name,
  u.email,
  u.role,
  u.is_active,
  sp.store_name,
  u.created_at
FROM public.users u
LEFT JOIN public.seller_profiles sp ON sp.user_id = u.id;

-- D. View Menu 5 (Tiket Laporan & Pengajuan Kreator)
CREATE OR REPLACE VIEW public.v_reports_detail AS
SELECT
  r.id,
  'RPT-' || r.id AS ticket_code,
  r.report_type,
  r.subject,
  r.description,
  r.status,
  r.admin_note,
  r.reviewed_by,
  r.reviewed_at,
  r.created_at,
  u.id AS reporter_id,
  COALESCE(sp.store_name, u.name) AS reporter_display_name,
  u.name AS reporter_name,
  u.role AS reporter_role,
  u.email AS reporter_email,
  a.id AS asset_id,
  a.title AS asset_title
FROM public.reports r
JOIN public.users u ON u.id = r.reporter_id
LEFT JOIN public.seller_profiles sp ON sp.user_id = u.id
LEFT JOIN public.assets a ON a.id = r.asset_id;

-- E. View Menu 6 & KPI Dashboard (Monitoring Transaksi & Komisi 10%)
CREATE OR REPLACE VIEW public.v_transactions_monitoring AS
SELECT
  t.id AS transaction_id,
  td.id AS detail_id,
  t.invoice_number,
  t.status,
  t.commission_rate,
  t.paid_at,
  t.created_at,
  u.id AS buyer_id,
  u.name AS buyer_name,
  u.email AS buyer_email,
  a.id AS asset_id,
  a.title AS asset_title,
  sp.store_name AS creator_name,
  td.price AS gross_amount,
  ROUND(td.price * (t.commission_rate / 100.0))::integer AS commission_amount,
  (td.price - ROUND(td.price * (t.commission_rate / 100.0))::integer) AS creator_net_amount
FROM public.transactions t
JOIN public.users u ON u.id = t.buyer_id
JOIN public.transaction_details td ON td.transaction_id = t.id
JOIN public.assets a ON a.id = td.asset_id
JOIN public.seller_profiles sp ON sp.user_id = a.seller_id;

-- 9. TRIGGERS SINKRONISASI ROLE & PROFIL KREATOR

-- A. Jika role user diubah ke 'Kreator' di Menu 4, otomatis buatkan seller_profiles jika belum ada
CREATE OR REPLACE FUNCTION public.fn_ensure_seller_profile()
RETURNS TRIGGER AS $$
BEGIN
  IF NEW.role = 'Kreator' THEN
    INSERT INTO public.seller_profiles (user_id, store_name)
    VALUES (NEW.id, NEW.name)
    ON CONFLICT (user_id) DO NOTHING;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_ensure_seller_profile
AFTER INSERT OR UPDATE OF role ON public.users
FOR EACH ROW
EXECUTE FUNCTION public.fn_ensure_seller_profile();

-- B. Jika tiket 'seller_application' di Menu 5 ditandai 'resolved', otomatis naikkan role pelapor jadi 'seller'
CREATE OR REPLACE FUNCTION public.fn_approve_seller_ticket()
RETURNS TRIGGER AS $$
BEGIN
  IF NEW.report_type = 'seller_application'
     AND NEW.status = 'SELESAI'
     AND (TG_OP = 'INSERT' OR OLD.status IS DISTINCT FROM 'SELESAI') THEN
    UPDATE public.users
    SET role = 'Kreator'
    WHERE id = NEW.reporter_id
      AND role = 'Pembeli';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_approve_seller_ticket
AFTER INSERT OR UPDATE OF status ON public.reports
FOR EACH ROW
EXECUTE FUNCTION public.fn_approve_seller_ticket();